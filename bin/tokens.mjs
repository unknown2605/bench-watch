#!/usr/bin/env node
// Writes the --sh-* CSS variables and text-style classes from design/figma-tokens.json; same input, same bytes.
import { readFileSync, renameSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';

const FONT_STACKS = {
  Oxanium: '"Oxanium", system-ui, sans-serif',
  'Share Tech Mono': '"Share Tech Mono", ui-monospace, monospace',
};
const CASES = { none: 'none', upper: 'uppercase' };

function fail(message) {
  process.stderr.write(`tokens: ${message}\n`);
  process.exit(1);
}

function slug(text) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function number(value) {
  return String(Number(value.toFixed(4)));
}

export function render(tokens) {
  const lines = ['/* Generated by bin/tokens.mjs from design/figma-tokens.json. Do not edit; run bin/generate.sh. */'];
  lines.push(':root {');
  const names = new Set();
  const claim = (name, owner) => {
    if (names.has(name)) fail(`${owner}: ${name} is generated twice`);
    names.add(name);
  };

  for (const [name, color] of Object.entries(tokens.colors ?? {})) {
    if (!/^#[0-9a-f]{6}$/.test(color.value)) fail(`${name}: colour must be #rrggbb in lower case`);
    if (!/^--sh-[a-z]+(-[a-z]+)*$/.test(color.web)) fail(`${name}: web name must be --sh-*`);
    claim(color.web, name);
    lines.push(`  ${color.web}: ${color.value};`);
  }

  const families = [...new Set(Object.values(tokens.textStyles ?? {}).map((s) => s.family))];
  for (const family of families) {
    if (!FONT_STACKS[family]) fail(`unknown font family ${JSON.stringify(family)}`);
    claim(`--sh-font-${slug(family)}`, family);
    lines.push(`  --sh-font-${slug(family)}: ${FONT_STACKS[family]};`);
  }

  const classes = [];
  for (const [name, style] of Object.entries(tokens.textStyles ?? {})) {
    const id = slug(name);
    claim(`.sh-text-${id}`, name);
    for (const part of ['size', 'weight', 'tracking']) claim(`--sh-text-${id}-${part}`, name);
    if (!Number.isInteger(style.weight) || style.weight < 100 || style.weight > 900) fail(`${name}: bad weight`);
    if (!(style.size > 0 && style.size <= 200)) fail(`${name}: bad size`);
    if (typeof style.letterSpacingPercent !== 'number') fail(`${name}: bad letter spacing`);
    if (!CASES[style.case]) fail(`${name}: case must be none or upper`);
    const tracking = style.letterSpacingPercent === 0 ? '0' : `${number(style.letterSpacingPercent / 100)}em`;
    lines.push(`  --sh-text-${id}-size: ${number(style.size)}px;`);
    lines.push(`  --sh-text-${id}-weight: ${style.weight};`);
    lines.push(`  --sh-text-${id}-tracking: ${tracking};`);
    classes.push(
      '',
      `.sh-text-${id} {`,
      `  font-family: var(--sh-font-${slug(style.family)});`,
      `  font-weight: var(--sh-text-${id}-weight);`,
      `  font-size: var(--sh-text-${id}-size);`,
      `  letter-spacing: var(--sh-text-${id}-tracking);`,
      '  line-height: normal;',
      `  text-transform: ${CASES[style.case]};`,
      '}',
    );
  }

  lines.push('}', ...classes, '');
  return lines.join('\n');
}

function main(argv) {
  const [input, output, flag] = argv;
  if (!input || !output || (flag && flag !== '--check')) {
    fail('usage: tokens.mjs <figma-tokens.json> <tokens.css> [--check]');
  }
  const css = render(JSON.parse(readFileSync(input, 'utf8')));
  if (flag === '--check') {
    let current = '';
    try {
      current = readFileSync(output, 'utf8');
    } catch {
      fail(`${output} is missing; run bin/generate.sh`);
    }
    if (current !== css) fail(`${output} is out of date; run bin/generate.sh`);
    return;
  }
  const temp = join(dirname(output), `.${basename(output)}.tmp`);
  writeFileSync(temp, css);
  renameSync(temp, output);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
